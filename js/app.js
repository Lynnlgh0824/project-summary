                const resp = await fetch('/api/logs');
                if (!resp.ok) throw new Error('HTTP ' + resp.status);
                const data = await resp.json();
                const rawLogs = (data && data.logs) || [];
                if (rawLogs.length === 0) return;

                // 转换为本系统日志格式，并按 id 去重
                const serverLogs = [];
                const seenIds = new Set();
                rawLogs.forEach(l => {
                    const mapped = SERVER_PROJECT_MAP[l.projectId] || null;
                    const id = l.id || ((l.projectId || 'x') + '-' + (l.date || '') + '-' + Math.random().toString(36).slice(2, 6));
                    if (seenIds.has(id)) return;
                    seenIds.add(id);
                    serverLogs.push({
                        id: id,
                        projectId: (mapped && mapped.id) || l.projectId,
                        projectName: (mapped && mapped.name) || l.projectName || l.projectId,
                        date: (l.date || '').split('T')[0],
                        datetime: l.datetime || l.date || '',
                        title: l.title || '',
                        tags: Array.isArray(l.tags) ? l.tags : [],
                        items: Array.isArray(l.items) ? l.items : [],
                        code: (typeof l.code === 'string') ? l.code : null,
                        isAutoGenerated: true
                    });
                });

                // 合并：服务器日志为权威，但保留本地手动新增（服务器没有的 id）的日志
                const existing = JSON.parse(localStorage.getItem(STORAGE_KEY) || '[]');
                const serverIds = new Set(serverLogs.map(l => l.id));
                const localOnly = Array.isArray(existing) ? existing.filter(l => !serverIds.has(l.id)) : [];
                const finalLogs = serverLogs.concat(localOnly);

                localStorage.setItem(STORAGE_KEY, JSON.stringify(finalLogs));

