        // 按项目筛选
        function filterByProject(projectId) {
            currentProjectFilter = projectId;

            // 更新顶部标题中的项目名称
            updateHeaderProjectName(projectId);

            renderProjectList();
            renderQuickAccess();
            renderAll();

            // 检查当前活跃的标签页并重新渲染内容
            const activeTabBtn = document.querySelector('.tab-btn.active');
            if (activeTabBtn) {
                const tabText = activeTabBtn.textContent;
                const tabRenderMap = {
                    '📚 项目总结': renderSummaryContent,
                    '📁 项目资源': renderProjectResources,
                    '✅ 待办清单': renderTodosContent,
                };
                const matched = Object.entries(tabRenderMap).find(([key]) => tabText.includes(key));
                if (matched) {
                    matched[1]();
                } else {
                    switchTab('logs');
                }
            } else {
                switchTab('logs');
            }
        }

