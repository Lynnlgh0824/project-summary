        function switchTab(tabName) {
            // 更新当前标签索引（用于滚动切换）
            const newIndex = tabOrder.indexOf(tabName);
            if (newIndex !== -1) {
                currentTabIndex = newIndex;
            }

            // 清除防抖定时器和滚动状态
            if (scrollTimeout) {
                clearTimeout(scrollTimeout);
                scrollTimeout = null;
            }
            isScrolling = false;

            // 锁定滚动切换1秒，防止手动点击后立即触发滚动切换
            tabLockedUntil = Date.now() + 1000;

            // 重置滚动位置到顶部
            const container = document.querySelector('.main');
            if (container) {
                container.scrollTop = 0;
                lastScrollPosition = 0;
            }

            // 隐藏所有标签页内容
            document.querySelectorAll('.tab-content').forEach(tab => {
                tab.style.display = 'none';
            });

            // 移除所有标签按钮的active状态
            document.querySelectorAll('.tab-btn').forEach(btn => {
                btn.classList.remove('active');
            });

            // 显示选中的标签页
            document.getElementById('tab-' + tabName).style.display = 'block';

            // 激活对应按钮（通过onclick事件或手动查找）
            if (event && event.target) {
                event.target.classList.add('active');
            } else {
                // 如果没有event对象，手动查找并激活对应按钮
                const tabs = {
                    'logs': '📅 工作日志',
                    'summary': '📚 项目总结',
                    'resources': '📁 项目资源',
                    'todos': '✅ 待办清单',
                    'timelog': '📊 用时分析',
                    'stats': '📈 数据统计',
                    'timestat': '⏱ 时间统计',
                    'todorecover': '🔧 待办恢复'
                };
                document.querySelectorAll('.tab-btn').forEach(btn => {
                    if (tabs[tabName] && btn.textContent.includes(tabs[tabName])) {
                        btn.classList.add('active');
                    }
                });
            }

            // 根据标签页渲染动态内容
            if (tabName === 'summary') {
                renderSummaryContent();
            } else if (tabName === 'resources') {
                renderProjectResources();
            } else if (tabName === 'todos') {
                renderTodosContent();
            } else if (tabName === 'timelog') {
                renderTimeLogContent();
            } else if (tabName === 'stats') {
                renderStatsContent();
            } else if (tabName === 'timestat') {
                renderTimeStatContent();
            } else if (tabName === 'todorecover') {
                renderTodoRecoverContent();
            }
        }

