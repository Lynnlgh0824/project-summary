        // 从今日日志提取待办事项
        function extractTodosFromTodayLog() {
            const logs = getLogs();
            const todos = getTodos();
            const projects = getProjects();
            const today = new Date().toISOString().split('T')[0];

            // 获取今天的日志
            const todayLogs = logs.filter(log => log.date === today);

            if (todayLogs.length === 0) {
                alert('今天还没有工作日志，请先添加日志再提取待办事项。');
                return;
            }

            let extractedCount = 0;
            const extractedByProject = {};

            // 待办事项关键词（中文和英文）
            const todoKeywords = [
                '待办', '待做', '未完成', 'TODO', 'todo', '待完成',
                '需要', '还需', '继续', '跟进', '处理',
                '解决', '修复', '优化', '添加', '实现'
            ];

            todayLogs.forEach(log => {
                if (!log.items || log.items.length === 0) return;

                // 获取项目名称
                const project = projects.find(p => p.id === log.projectId);
                const projectName = project ? project.name : log.projectName || '未知项目';

                // 确保该项目有待办数组
                if (!todos[log.projectId]) {
                    todos[log.projectId] = [];
                }

                // 初始化该项目计数
                if (!extractedByProject[log.projectId]) {
                    extractedByProject[log.projectId] = { name: projectName, count: 0 };
                }

                log.items.forEach(item => {
                    const trimmedItem = item.trim();

                    // 跳过已完成的项目（以✅开头的）
                    if (trimmedItem.startsWith('✅') || trimmedItem.startsWith('完成')) {
                        return;
                    }

                    // 检查是否包含待办关键词
                    const hasTodoKeyword = todoKeywords.some(keyword =>
                        trimmedItem.toLowerCase().includes(keyword.toLowerCase())
                    );

                    if (hasTodoKeyword) {
                        // 清理文本，移除符号
                        let cleanText = trimmedItem
                            .replace(/^[■●▪·-]\s*/, '')  // 移除开头的项目符号
                            .replace(/^(待办|TODO|todo):?\s*/i, '')  // 移除待办标记
                            .trim();

                        // 检查是否已存在相同的待办
                        const exists = todos[log.projectId].some(t =>
                            t.text === cleanText || t.text === trimmedItem
                        );

                        if (!exists && cleanText.length > 0) {
                            // 根据关键词判断优先级
                            let priority = 'medium';
                            if (cleanText.includes('紧急') || cleanText.includes('重要') || cleanText.includes('!!!')) {
                                priority = 'high';
                            } else if (cleanText.includes('优化') || cleanText.includes('改进')) {
                                priority = 'low';
                            }

                            const newTodo = {
                                id: Date.now().toString() + Math.random().toString(36).substr(2, 9),
                                text: cleanText,
                                status: 'pending',
                                priority: priority,
                                dueDate: null,
                                createdAt: new Date().toISOString(),
                                source: 'today-log'
                            };

                            todos[log.projectId].push(newTodo);
                            extractedCount++;
                            extractedByProject[log.projectId].count++;
                        }
                    }
                });
            });

            if (extractedCount === 0) {
                alert('今天的日志中没有找到待办事项。\n\n提示：日志中包含"待办"、"未完成"、"需要"、"继续"等关键词的内容会被识别为待办事项。');
                return;
            }

            saveTodos(todos);
            renderTodosContent();

            // 构建详细的消息
            let message = `✅ 成功从今日日志提取了 ${extractedCount} 个待办事项！\n\n`;
            Object.values(extractedByProject).forEach(({ name, count }) => {
                message += `• ${name}: ${count} 个\n`;
            });

            alert(message);
        }

